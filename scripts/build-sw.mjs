// next build（静的エクスポート）後に out/ を走査し、プリキャッシュ一覧付きの sw.js を生成する。
// アプリシェル・空港データ・地図データ・MapLibre ワーカーをすべてキャッシュし、完全オフラインで動作させる。
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const OUT = "out";
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(OUT);

const hash = createHash("sha256");
const urls = [];
for (const f of files.sort()) {
  const rel = relative(OUT, f).split(sep).join("/");
  if (rel === "sw.js" || rel.endsWith(".map")) continue;
  hash.update(rel).update(readFileSync(f));
  // index.html はディレクトリ URL（/log/）で参照される
  urls.push("/" + rel.replace(/(^|\/)index\.html$/, "$1"));
}
const version = hash.digest("hex").slice(0, 12);

const sw = `/* StudyFlight service worker — generated by scripts/build-sw.mjs */
const VERSION = ${JSON.stringify(version)};
const CACHE = "studyflight-" + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      // 1件の失敗で全体が失敗しないよう個別に追加
      await Promise.all(PRECACHE.map((url) => cache.add(new Request(url, { cache: "reload" })).catch(() => undefined)));
    }),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) if (key.startsWith("studyflight-") && key !== CACHE) await caches.delete(key);
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

function normalize(url) {
  let path = url.pathname;
  if (!path.endsWith("/") && !/\\.[a-z0-9]+$/i.test(path)) path += "/";
  return path;
}

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const key = normalize(url);
      const hit = await cache.match(key, { ignoreSearch: true });
      if (hit) return hit;
      try {
        const res = await fetch(req);
        // 同一オリジンの静的アセットは実行時にもキャッシュ
        if (res.ok && url.pathname.startsWith("/_next/static/")) cache.put(req, res.clone());
        return res;
      } catch (err) {
        if (req.mode === "navigate") {
          const shell = (await cache.match("/", { ignoreSearch: true })) || (await cache.match("/404.html"));
          if (shell) return shell;
        }
        throw err;
      }
    })(),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`[sw] version ${version}, ${urls.length} files precached`);
